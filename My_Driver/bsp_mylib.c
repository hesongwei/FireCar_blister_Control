/********************************************************************************
* @fun	  BCDToInt
* @brief  BCD转成整形
* @param  bcd c传入数据 len 转化数量
* @retval 无
* @author 之风
* @data   2019.11.4 晚
  ********************************************************************************/
uint8_t BCDToInt(uint8_t *bcd, uint8_t len) //BCD转十进制
{
    uint8_t num = 0;
    for (num = 0; num < len; num++)
    {
        *bcd = (0xff & (*bcd >> 4)) * 10 + (0xf & *bcd);
        bcd++;
    }
    return 0;
}

/********************************************************************************
* @fun	  DectoBCD
* @brief  十进制转换成BCD码
* @param  无
* @retval 无
* @author 之风
* @data   2019.11.4 晚
  ********************************************************************************/
void DectoBCD(uint16_t Dec, uint8_t *Bcd, int8_t length)
{
    int8_t i;
    uint16_t temp;
    for (i = length - 1; i >= 0; i--)
    {
        temp = Dec % 100;
        Bcd[i] = ((temp / 10) << 4) + ((temp % 10) & 0x0F);
        Dec /= 100;
    }
}

/********************************************************************************
*	@fun    Get_Bit_1_Num
*   @brief  计算一个变量里有多少个1
*   @param  data 要计算的值
*   @retval 有多少个1的数量
*	@author 之风
*   @data   2019.6.12 晚
********************************************************************************/
uint8_t Get_Bit_1_Num(uint32_t data)
{
    uint8_t num = 0;
    uint8_t count = 0;
    for (; num < 32; num++)
    {
        if (data & 1)
            count++;
        data >>= 1;
    }
    return count;
}

