/*
*********************************************************************************************************
*    函 数 名: str_cmp
*    功能说明: 字符串比较
*    形    参: s1 : 字符串1
*              s2 : 字符串2
*    返 回 值: 0 表示相等 非0表示不等
*********************************************************************************************************
*/
int str_cmp(char *s1, char *s2)
{
    while ((*s1 != 0) && (*s2 != 0) && (*s1 == *s2))
    {
        s1++;
        s2++;
    }
    return *s1 - *s2;
}

