/********************************************************************************
*   @fun        XOR_Verify
*   @brief      异或校验
*   @param      *pdata 传入直针 len 长度
*   @retval     data_varify
*   @author     之风
*   @data       2019.6.12 晚
********************************************************************************/
uint8_t XOR_Verify(uint8_t *pdata, uint8_t len)
{
    uint8_t num = 0;
    data_varify=0;
    for (num = 0; num < len; num++)
        data_varify ^= *pdata++; //首先进来data_varify给初值为0，0异或任何数都是原来的

    return data_varify;
}

/********************************************************************************
*   @fun    SunVerify_Fun
*   @brief  和校验
*   @param  *pdata 传入直针 len 长度
*   @retval 
*   @author 之风
*   @data   2019.6.12 晚
********************************************************************************/
uint8_t SunVerify_Fun(uint8_t *pdata, uint8_t len)
{
    uint8_t num = 0;
    data_varify=0;
    for (num = 0; num < len; num++)
        data_varify += *pdata++;
    return data_varify;
}

/********************************************************************************
* @fun	  C_SunVerify_Fun
* @brief  和校验后取反+1
* @param  *pdata 传入直针 len 长度
* @retval 
* @author 之风
* @data   2019.6.12 晚
********************************************************************************/
uint8_t C_SunVerify_Fun(uint8_t *pdata, uint8_t len)
{
    uint8_t num = 0;
    data_varify=0;
    for (num = 0; num < len; num++)
        data_varify += *pdata++;
    data_varify = (~data_varify) + 1;
    return data_varify;
}
