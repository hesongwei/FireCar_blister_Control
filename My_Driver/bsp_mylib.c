uint32_t LEBufToUint32(uint8_t *_pBuf)
{
    return (((uint32_t)_pBuf[3] << 24) | ((uint32_t)_pBuf[2] << 16) | ((uint32_t)_pBuf[1] << 8) | _pBuf[0]);
}

/*
*********************************************************************************************************
*    函 数 名: CaculTwoPoint
*    功能说明: 根据2点直线方程，计算Y值
*    形    参:  2个点的坐标和x输入量
*    返 回 值: x对应的y值
*********************************************************************************************************
*/
int32_t CaculTwoPoint(int32_t x1, int32_t y1, int32_t x2, int32_t y2, int32_t x)
{
    if (x2 == x1)
    {
        return 0;
    }
    return y1 + ((int64_t)(y2 - y1) * (x - x1)) / (x2 - x1);
}

/*
*********************************************************************************************************
*    函 数 名: CaculTwoPointFloat
*    功能说明: 根据2点直线方程，计算Y值。 浮点
*    形    参:  2个点的坐标和x输入量
*    返 回 值: x对应的y值
*********************************************************************************************************
*/
float CaculTwoPointFloat(float x1, float y1, float x2, float y2, float x)
{
    if (x2 == x1)
    {
        return 0;
    }
    return y1 + ((y2 - y1) * (x - x1)) / (x2 - x1);
}

/*
*********************************************************************************************************
*    函 数 名: BcdToChar
*    功能说明: 将BCD码转为ASCII字符。 比如 0x0A ==> 'A'
*    形    参: _bcd   ：输入的二进制数。必须小于16
*    返 回 值: 转换结果
*********************************************************************************************************
*/
char BcdToChar(uint8_t _bcd)
{
    if (_bcd < 10)
    {
        return _bcd + '0';
    }
    else if (_bcd < 16)
    {
        return _bcd - 10 + 'A';
    }
    else
    {
        return 0;
    }
}

/*
*********************************************************************************************************
*    函 数 名: HexToAscll
*    功能说明: 将二进制数组转换为16进制格式的ASCII字符串。每个2个ASCII字符后保留1个空格。
*              0x12 0x34 转化为 0x31 0x32 0x20 0x33 0x34 0x00  即 "1234"
*    形    参:     _pHex   ：输入的数据，二进制数组
*                _pAscii ：存放转换结果, ASCII字符串，0结束。1个二进制对应2个ASCII字符.
*    返 回 值: 转换得到的整数
*********************************************************************************************************
*/
void HexToAscll(uint8_t *_pHex, char *_pAscii, uint16_t _BinBytes)
{
    uint16_t i;

    if (_BinBytes == 0)
    {
        _pAscii[0] = 0;
    }
    else
    {
        for (i = 0; i < _BinBytes; i++)
        {
            _pAscii[3 * i] = BcdToChar(_pHex[i] >> 4);
            _pAscii[3 * i + 1] = BcdToChar(_pHex[i] & 0x0F);
            _pAscii[3 * i + 2] = ' ';
        }
        _pAscii[3 * (i - 1) + 2] = 0;
    }
}

/*
*********************************************************************************************************
*    函 数 名: AsciiToHex
*    功能说明: 将ASCII字符串转换为 二进制数组。自动过滤空格。
*              "FF 12 34 F0" 转化为 0xFF,0x12,0x34,0xF0
*    形    参: _pAscii ：存放转换结果, ASCII字符串，0结束。1个二进制对应2个ASCII字符.
*              _pHex   ：输入的数据，二进制数组      
*              _MaxLen : _pHex 数组最大长度
*    返 回 值: 转换数组长度. 
*********************************************************************************************************
*/
uint16_t AsciiToHex(char *_pAscii, uint8_t *_pHex, uint16_t _MaxLen)
{
    uint32_t hexlen;
    char buf[2];
    char idx = 0;
    char ch;

    hexlen = 0;
    while (*_pAscii != 0)
    {
        ch = *_pAscii;
        if (ch == ' ' || ch == '\t')
        {
            _pAscii++;
            continue;
        }

        if (((ch >= 'A') && (ch <= 'F')) ||
            ((ch >= 'a') && (ch <= 'f')) ||
            ((ch >= '0') && (ch <= '9')))
        {
            buf[idx++] = *_pAscii++;
            if (idx == 2)
            {
                _pHex[hexlen++] = TwoCharToInt(buf);

                if (hexlen == _MaxLen)
                {
                    break;
                }

                idx = 0;
            }
        }
        else
        {
            hexlen = 0; /* 格式错误，返回0 */
            break;
        }
    }

    return hexlen;
}

/*
*********************************************************************************************************
*    函 数 名: AsciiToUint32
*    功能说明: 变长的 ASCII 字符转换为32位整数  ASCII 字符以空格或者0结束 。 支持16进制和10进制输入
*    形    参: *pAscii ：要转换的ASCII码
*    返 回 值: 转换得到的整数
*********************************************************************************************************
*/
uint32_t AsciiToUint32(char *pAscii)
{
    char i;
    char bTemp;
    char bIsHex;
    char bLen;
    char bZeroLen;
    uint32_t lResult;
    uint32_t lBitValue;

    /* 判断是否是16进制数 */
    bIsHex = 0;
    if ((pAscii[0] == '0') && ((pAscii[1] == 'x') || (pAscii[1] == 'X')))
    {
        bIsHex = 1;
    }

    lResult = 0;
    // 最大数值为 4294967295, 10位+2字符"0x" //
    if (bIsHex == 0)
    { // 十进制 //
        // 求长度 //
        lBitValue = 1;

        /* 前导去0 */
        for (i = 0; i < 8; i++)
        {
            bTemp = pAscii[i];
            if (bTemp != '0')
                break;
        }
        bZeroLen = i;

        for (i = 0; i < 10; i++)
        {
            if ((pAscii[i] < '0') || (pAscii[i] > '9'))
                break;
            lBitValue = lBitValue * 10;
        }
        bLen = i;
        lBitValue = lBitValue / 10;
        if (lBitValue == 0)
            lBitValue = 1;
        for (i = bZeroLen; i < bLen; i++)
        {
            lResult += (pAscii[i] - '0') * lBitValue;
            lBitValue /= 10;
        }
    }
    else
    { /* 16进制 */
        /* 求长度 */
        lBitValue = 1;

        /* 前导去0 */
        for (i = 0; i < 8; i++)
        {
            bTemp = pAscii[i + 2];
            if (bTemp != '0')
                break;
        }
        bZeroLen = i;
        for (; i < 8; i++)
        {
            bTemp = pAscii[i + 2];
            if (((bTemp >= 'A') && (bTemp <= 'F')) ||
                ((bTemp >= 'a') && (bTemp <= 'f')) ||
                ((bTemp >= '0') && (bTemp <= '9')))
            {
                lBitValue = lBitValue * 16;
            }
            else
            {
                break;
            }
        }
        lBitValue = lBitValue / 16;
        if (lBitValue == 0)
            lBitValue = 1;
        bLen = i;
        for (i = bZeroLen; i < bLen; i++)
        {
            bTemp = pAscii[i + 2];
            if ((bTemp >= 'A') && (bTemp <= 'F'))
            {
                bTemp -= 0x37;
            }
            else if ((bTemp >= 'a') && (bTemp <= 'f'))
            {
                bTemp -= 0x57;
            }
            else if ((bTemp >= '0') && (bTemp <= '9'))
            {
                bTemp -= '0';
            }
            lResult += bTemp * lBitValue;
            lBitValue /= 16;
        }
    }
    return lResult;
}

/*
*********************************************************************************************************
*    函 数 名: CharToInt
*    功能说明: 1个HEX格式ASCII字符转换为整数值0-F
*    形    参: chr : 字符
*    返 回 值: 整数值
*********************************************************************************************************
*/
uint8_t CharToInt(char _ch)
{
    uint8_t itemp;

    if ((_ch >= '0') && (_ch <= '9'))
    {
        itemp = _ch - '0';
    }
    else if (_ch >= 'a' && _ch <= 'f')
    {
        itemp = _ch - 'a' + 0x0A;
    }
    else if (_ch >= 'A' && _ch <= 'F')
    {
        itemp = _ch - 'A' + 0x0A;
    }
    else
    {
        itemp = 0;
    }

    return itemp;
}

/*
*********************************************************************************************************
*    函 数 名: TwoCharToInt
*    功能说明: 2个HEX格式ASCII字符转换为整数值0-F
*    形    参: chr : 字符
*    返 回 值: 整数值
*********************************************************************************************************
*/
uint8_t TwoCharToInt(char *_ch)
{
    uint8_t temp;

    temp = CharToInt(_ch[0]) * 16;
    temp += CharToInt(_ch[1]);

    return temp;
}

